// Package generate emits Go, TypeScript, and JSON from resolved Plug metadata.
// Its inputs come from [schema.RuntimeSchema] and are read-only during generation.
package generate

import (
	"fmt"
	"strconv"

	"go.astrophena.name/plug"
	"go.astrophena.name/plug/internal/names"
)

// runtimeImport is the Plug runtime path used by generated bindings.
const runtimeImport = "go.astrophena.name/plug"

const implementationImport = runtimeImport + "/plugimpl"

// Go returns deterministic native Go bindings for s.
func Go(s plug.Schema) ([]byte, error) {
	g := generator{
		goGenerator: newGoGenerator(newModel(s), true),
	}

	return formatGo(g.generate(), "Go")
}

type generator struct {
	goGenerator
}

func (g *generator) generate() []byte {
	g.line("// Code generated by plug; DO NOT EDIT.")
	g.line("")
	g.writeGoPackageDoc("Plug bindings")
	g.line("package %s", g.schema.Package)
	g.line("")
	g.writeImports()
	g.writeIDs()
	g.writePermissions()
	g.writeTypes()
	g.writeRequests()
	g.writeJSON()
	g.writeSchema()
	g.writeCodecs()
	g.writeMethods()
	g.writeHandlers()
	g.writeClient()
	g.writeHTTPRoutes()
	return g.buf.Bytes()
}

func (g *generator) writeImports() {
	g.line("import (")
	if len(g.schema.Methods) > 0 {
		g.line("\t\"context\"")
	}
	if g.hasRawMethods() {
		g.line("\t\"net\"")
	}
	if g.hasHTTP && g.hasSums() {
		g.line("\t\"encoding/json/v2\"")
	}
	if g.hasHTTP && g.hasSumFields() {
		g.line("\t\"encoding/json/jsontext\"")
	}
	if (g.hasHTTP && g.hasSums()) || g.errorFieldsNeedFmt() {
		g.line("\t\"fmt\"")
	}
	if len(g.errorConstructors) > 0 {
		g.line("\t\"errors\"")
	}
	g.line("\tplug %q", runtimeImport)
	g.line("\tplugimpl %q", implementationImport)
	if g.hasHTTP {
		g.line("\tplughttp %q", runtimeImport+"/plughttp")
	}
	g.line(")")
	g.line("")
}

func (g *generator) writeIDs() {
	var constructors []constructor
	for _, c := range g.constructors {
		if typ := g.types[c.result]; typ.Kind == plug.TypeSum || typ.Error {
			constructors = append(constructors, c)
		}
	}
	if len(constructors) == 0 && len(g.methods) == 0 {
		return
	}

	g.line("const (")
	for _, c := range constructors {
		name := constructorIDName(c.Name)
		g.line("\t%s uint32 = 0x%08x", name, c.ID)
	}
	if len(constructors) > 0 && len(g.methods) > 0 {
		g.line("")
	}
	for _, m := range g.methods {
		name := methodIDName(m.Name)
		g.line("\t%s uint32 = 0x%08x", name, m.ID)
	}
	g.line(")")
	g.line("")
}

func (g *generator) writePermissions() {
	if len(g.schema.Permissions) == 0 {
		return
	}

	for _, p := range g.schema.Permissions {
		name := "Permission" + names.Go(p.Name)
		g.doc(name, p.Name, fmt.Sprintf("is the %s authorization capability.", p.Name), p.Documentation)
		g.line("const %s = %s", name, strconv.Quote(p.Name))
		g.line("")
	}
}

func (g *generator) hasSums() bool {
	for _, name := range g.groupNames {
		if len(g.types[name].Constructors) > 1 {
			return true
		}
	}
	return false
}

func (g *generator) errorFieldsNeedFmt() bool {
	for _, c := range g.errorConstructors {
		if len(c.Fields) > 0 {
			return true
		}
	}
	return false
}
