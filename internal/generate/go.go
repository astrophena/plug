const (
	runtimeImport        = "go.astrophena.name/plug"
	implementationImport = runtimeImport + "/plugimpl"
)

// Go returns native Go bindings for s.
func Go(s plug.Schema) ([]byte, error) {
	g := generator{
		goGenerator: newGoGenerator(newModel(s), true),
	}

	return formatGo(g.generate(), "Go")
}

type generator struct {
	goGenerator
}

func (g *generator) generate() []byte {
	g.line("// Code generated by plug; DO NOT EDIT.")
	g.line("")
	g.writeGoPackageDoc("Plug bindings")
	g.line("package %s", g.schema.Package)
	g.line("")
	g.writeImports()
	g.writeIDs()
	g.writePermissions()
	g.writeTypes()
	g.writeRequests()
	g.writeJSON()
	g.writeSchema()
	g.writeCodecs()
	g.writeMethods()
	g.writeHandlers()
	g.writeClient()
	g.writeHTTPRoutes()
	return g.buf.Bytes()
}

func (g *generator) writeImports() {
	g.line("import (")
	if len(g.schema.Methods) > 0 {
		g.line("\t\"context\"")
	}
	if g.hasRawMethods() {
		g.line("\t\"net\"")
	}
	if g.hasHTTP && (g.hasSums() || g.hasHTTPFields()) {
		g.line("\t\"encoding/json/v2\"")
	}
	if g.hasHTTP && (g.hasSumFields() || g.hasHTTPFields()) {
		g.line("\t\"encoding/json/jsontext\"")
	}
	if (g.hasHTTP && g.hasSums()) || g.hasHTTPFields() || g.errorFieldsNeedFmt() {
		g.line("\t\"fmt\"")
	}
	if len(g.errorConstructors) > 0 {
		g.line("\t\"errors\"")
	}
	g.line("\tplug %q", runtimeImport)
	g.line("\tplugimpl %q", implementationImport)
	if g.hasHTTP {
		g.line("\tplughttp %q", runtimeImport+"/plughttp")
	}
	g.line(")")
	g.line("")
}

func (g *generator) writeIDs() {
	var constructors []constructor
	for _, c := range g.constructors {
		if typ := g.types[c.result]; typ.Kind == plug.TypeSum || typ.Error {
			constructors = append(constructors, c)
		}
	}
	if len(constructors) == 0 && len(g.methods) == 0 {
		return
	}

	g.line("const (")
	for _, c := range constructors {
		name := constructorIDName(c.Name)
		g.line("\t%s uint32 = 0x%08x", name, c.ID)
	}
	if len(constructors) > 0 && len(g.methods) > 0 {
		g.line("")
	}
	for _, m := range g.methods {
		name := methodIDName(m.Name)
		g.line("\t%s uint32 = 0x%08x", name, m.ID)
	}
	g.line(")")
	g.line("")
}

func (g *generator) writePermissions() {
	if len(g.schema.Permissions) == 0 {
		return
	}

	for _, p := range g.schema.Permissions {
		name := "Permission" + names.Go(p.Name)
		g.doc(name, p.Name, fmt.Sprintf("is the %s permission.", p.Name), p.Documentation)
		g.line("const %s = %s", name, strconv.Quote(p.Name))
		g.line("")
	}
}

func (g *generator) hasSums() bool {
	for _, name := range g.groupNames {
		if len(g.types[name].Constructors) > 1 {
			return true
		}
	}
	return false
}

func (g *generator) errorFieldsNeedFmt() bool {
	for _, c := range g.errorConstructors {
		if len(c.Fields) > 0 {
			return true
		}
	}
	return false
}

func formatGo(source []byte, target string) ([]byte, error) {
	formatted, err := format.Source(source)
	if err != nil {
		return nil, fmt.Errorf("formatting generated %s: %w\n%s", target, err, source)
	}
	return formatted, nil
}

// goGenerator emits declarations shared by both Go generators.
type goGenerator struct {
	model
	emitter
	optPrefix string
	native    bool
}

func newGoGenerator(m model, native bool) goGenerator {
	optPrefix := ""
	if native {
		optPrefix = "plug."
	}
	return goGenerator{
		model:     m,
		indent:    "\t",
		docs:      doc.NewParser(&m.schema),
		optPrefix: optPrefix,
		native:    native,
	}
}

func (g *goGenerator) goType(ref plug.TypeExpr) string {
	var base string
	if ref.Element != nil {
		base = "[]" + g.goType(*ref.Element)
	} else if ref.Kind == plug.TypeExprPrimitive {
		base = primitiveGoType(ref.Name)
	} else {
		base = names.Go(ref.Name)
	}

	if ref.Optional {
		base = g.optPrefix + "Option[" + base + "]"
	}
	return base
}

func (g *goGenerator) typeContainsSum(ref plug.TypeExpr) bool {
	if ref.Element != nil {
		return g.typeContainsSum(*ref.Element)
	}
	return len(g.types[ref.Name].Constructors) > 1
}

func (g *goGenerator) writeStruct(name string, fields []plug.FieldInfo) {
	if len(fields) == 0 {
		g.line("type %s struct{}", name)
		g.line("")
		return
	}

	g.line("type %s struct {", name)
	for _, f := range fields {
		var (
			fieldName = names.Go(f.Name)
			tag       = "`json:\"" + f.Name
		)
		if f.Type.Optional {
			tag += ",omitzero"
		}
		tag += "\"`"

		g.docIndented(fieldName, f.Name, fmt.Sprintf("is the %s schema field.", f.Name), f.Documentation)
		g.line("\t%s %s %s", fieldName, g.goType(f.Type), tag)
	}
	g.line("}")
	g.line("")
}

func (g *goGenerator) writeErrorMethod(goName, ctorName string, fields []plug.FieldInfo) {
	if len(fields) == 0 {
		g.line("func (*%s) Error() string { return %q }", goName, ctorName)
		return
	}

	g.line("func (e *%s) Error() string {", goName)

	var (
		format strings.Builder
		args   []string
	)
	format.WriteString(ctorName)
	format.WriteString(":")
	for _, f := range fields {
		format.WriteString(" ")
		format.WriteString(f.Name)
		format.WriteString("=%v")
		args = append(args, "e."+names.Go(f.Name))
	}

	g.line("\treturn fmt.Sprintf(%s, %s)", strconv.Quote(format.String()), strings.Join(args, ", "))
	g.line("}")
}

func (g *goGenerator) writeRequests() {
	for _, m := range g.methods {
		if len(m.Fields) == 0 {
			continue
		}
		name := names.GoMethod(m.Name) + "Request"
		g.line("// %s contains the request fields for %s.", name, m.Name)
		g.writeStruct(name, m.Fields)
	}
}

func (g *goGenerator) writeTypes() {
	for _, nt := range g.newtypes {
		goName := names.Go(nt.Name)
		g.doc(goName, nt.Name, fmt.Sprintf("is the distinct Plug scalar %s.", nt.Name), nt.Documentation)
		g.line("type %s %s", goName, primitiveGoType(nt.Underlying))
		g.line("")
	}

	for _, name := range g.groupNames {
		ctors := g.types[name].Constructors
		if len(ctors) == 1 {
			var (
				c      = ctors[0]
				goName = names.Go(name)
			)

			g.doc(goName, c.Name, fmt.Sprintf("is the Plug record %s.", name), c.Documentation)
			g.writeStruct(goName, c.Fields)

			if g.types[name].Error {
				g.line("// Error returns the constructor name and fields.")
				g.writeErrorMethod(goName, c.Name, c.Fields)
				g.line("")
			}
			continue
		}

		var (
			goName = names.Go(name)
			sumDoc = g.types[name].Documentation
		)

		g.doc(goName, name, fmt.Sprintf("is the sealed Plug sum %s.", name), sumDoc)
		g.line("type %s interface {", goName)
		g.line("\tplug%s()", goName)
		if g.types[name].Error {
			g.line("\terror")
		}
		g.line("}")
		g.line("")

		for _, c := range ctors {
			variant := names.Go(c.Name)

			g.doc(variant, c.Name, fmt.Sprintf("is the %s variant of %s.", c.Name, name), c.Documentation)
			g.writeStruct(variant, c.Fields)
			g.line("func (*%s) plug%s() {}", variant, goName)
			g.line("")

			if g.types[name].Error {
				g.line("// Error returns the constructor name and fields.")
				g.writeErrorMethod(variant, c.Name, c.Fields)
				g.line("")
			}
		}

		unknown := "Unknown" + goName
		g.line("// %s preserves a sum constructor unknown to this schema generation.", unknown)
		g.line("type %s struct {", unknown)
		if g.native {
			g.line("\t// ConstructorID is the unknown wire constructor ID.")
			g.line("\tConstructorID uint32")
			g.line("\t// Payload is the uninterpreted constructor body.")
			g.line("\tPayload []byte")
		} else {
			g.line("\t// Constructor is the unfamiliar JSON constructor name.")
			g.line("\tConstructor string")
			g.line("\t// Payload is the complete JSON object received from the server.")
			g.line("\tPayload jsontext.Value")
		}
		g.line("}")
		g.line("")
		g.line("func (*%s) plug%s() {}", unknown, goName)
		g.line("")

		if g.types[name].Error {
			g.line("// Error reports an unknown constructor.")
			if g.native {
				g.line("func (*%s) Error() string { return %q }", unknown, "unknown "+name)
			} else {
				g.line("func (u *%s) Error() string {", unknown)
				g.line("\treturn fmt.Sprintf(\"unknown %s constructor %%q\", u.Constructor)", name)
				g.line("}")
			}
			g.line("")
		}
	}
}

type methodShape struct {
	name      string
	request   string
	response  string
	raw       bool
	void      bool
	noRequest bool
}

func (m methodShape) registrationFunc() string {
	switch {
	case m.raw && m.noRequest:
		return "AppendRawHandlerNoReq"
	case m.raw:
		return "AppendRawHandler"
	case m.noRequest && m.void:
		return "AppendHandlerNoReqVoid"
	case m.noRequest:
		return "AppendHandlerNoReq"
	case m.void:
		return "AppendHandlerVoid"
	default:
		return "AppendHandler"
	}
}

func (g *goGenerator) methodShape(m plug.MethodInfo) methodShape {
	var (
		name     = names.GoMethod(m.Name)
		raw      = isRaw(m.Response)
		response string
	)
	if !raw {
		response = g.goType(m.Response)
	}

	request := name + "Request"
	if len(m.Fields) == 0 {
		request = "plugimpl.Void"
	}

	return methodShape{
		name:      name,
		request:   request,
		response:  response,
		raw:       raw,
		void:      m.Response.Name == "void" && m.Response.Element == nil && !m.Response.Optional,
		noRequest: len(m.Fields) == 0,
	}
}

func primitiveGoType(name string) string {
	switch name {
	case "bool":
		return "bool"
	case "bytes":
		return "[]byte"
	case "f64":
		return "float64"
	case "i32":
		return "int32"
	case "i64":
		return "int64"
	case "string":
		return "string"
	case "u32":
		return "uint32"
	case "u64":
		return "uint64"
	case "void":
		return "plugimpl.Void"
	default:
		panic("unknown primitive " + name)
	}
}

func (g *generator) writeMethods() {
	for _, m := range g.methods {
		var (
			goName       = names.GoMethod(m.Name)
			name         = methodName(m.Name)
			errorsCodec  = "plugimpl.ErrorCodec{}"
			requestCodec = codecName(goName + "Request")
		)
		if m.Error != "" {
			errorsCodec = errorCodecName(m.Error)
		}
		if len(m.Fields) == 0 {
			requestCodec = "plugimpl.VoidCodec"
		}

		if isRaw(m.Response) {
			g.line("var %s = plugimpl.NewRawMethod(", name)
			g.line("\t&Schema,")
			g.line("\t%s,", methodIDName(m.Name))
			g.line("\t%s,", requestCodec)
			g.line("\t%s,", errorsCodec)
			g.line(")")
			g.line("")
			continue
		}

		g.line("var %s = plugimpl.NewMethod(", name)
		g.line("\t&Schema,")
		g.line("\t%s,", methodIDName(m.Name))
		g.line("\t%s,", requestCodec)
		g.line("\t%s,", g.codec(m.Response))
		g.line("\t%s,", errorsCodec)
		g.line(")")
		g.line("")
	}
}

func (g *generator) writeHandlers() {
	g.line("// Handlers contains the service method handlers.")
	g.line("type Handlers struct {")
	for _, m := range g.methods {
		shape := g.methodShape(m)
		g.line("\t// %s handles %s.", shape.name, m.Name)
		if shape.raw {
			if shape.noRequest {
				g.line("\t%s func(context.Context, *plug.RawStream) error", shape.name)
			} else {
				g.line("\t%s func(context.Context, %s, *plug.RawStream) error", shape.name, shape.request)
			}
			continue
		}
		if shape.noRequest && shape.void {
			g.line("\t%s func(context.Context) error", shape.name)
		} else if shape.noRequest {
			g.line("\t%s func(context.Context) (%s, error)", shape.name, shape.response)
		} else if shape.void {
			g.line("\t%s func(context.Context, %s) error", shape.name, shape.request)
		} else {
			g.line("\t%s func(context.Context, %s) (%s, error)", shape.name, shape.request, shape.response)
		}
	}
	g.line("}")
	g.line("")

	g.line("// RegisterHandlers registers every handler with server atomically. All fields must be non-nil.")
	g.line("func RegisterHandlers(server *plug.Server, h Handlers) error {")
	g.line("\tbatch := make([]plugimpl.Registration, 0, %d)", len(g.methods))
	for _, m := range g.methods {
		shape := g.methodShape(m)
		g.line("\tif err := plugimpl.%s(&batch, %s, h.%s, %q); err != nil {", shape.registrationFunc(), methodName(m.Name), shape.name, shape.name)
		g.line("\t\treturn err")
		g.line("\t}")
	}
	g.line("")

	g.line("\treturn server.RegisterHandlers(batch)")
	g.line("}")
	g.line("")
}

func (g *generator) writeClient() {
	g.line("// Client is the typed %s client.", g.schema.Package)
	g.line("type Client struct {")
	g.line("\traw *plug.Client")
	g.line("}")
	g.line("")

	g.line("// NewClient returns a typed wrapper around raw.")
	g.line("func NewClient(raw *plug.Client) *Client { return &Client{raw: raw} }")
	g.line("")

	g.line("// Close closes the underlying Plug client.")
	g.line("func (c *Client) Close() error { return c.raw.Close() }")
	g.line("")

	for _, m := range g.methods {
		shape := g.methodShape(m)
		if shape.raw {
			g.doc("Open"+shape.name, m.Name, fmt.Sprintf("opens a dedicated connection for %s.", m.Name), m.Documentation)
			if shape.noRequest {
				g.line("func Open%s(ctx context.Context, conn net.Conn, opts plug.ClientOptions) (plug.RawConn, error) {", shape.name)
				g.line("\treturn plug.OpenRaw(ctx, conn, %s, plugimpl.Void{}, opts)", methodName(m.Name))
			} else {
				g.line("func Open%s(ctx context.Context, conn net.Conn, req %s, opts plug.ClientOptions) (plug.RawConn, error) {", shape.name, shape.request)
				g.line("\treturn plug.OpenRaw(ctx, conn, %s, req, opts)", methodName(m.Name))
			}
			g.line("}")
			g.line("")
			continue
		}

		g.doc(shape.name, m.Name, fmt.Sprintf("calls %s.", m.Name), m.Documentation)
		if shape.noRequest && shape.void {
			g.line("func (c *Client) %s(ctx context.Context) error {", shape.name)
			g.line("\t_, err := c.raw.Call(ctx, %s, plugimpl.Void{})", methodName(m.Name))
			g.line("\treturn err")
			g.line("}")
		} else if shape.noRequest {
			g.line("func (c *Client) %s(ctx context.Context) (%s, error) {", shape.name, shape.response)
			g.line("\treturn c.raw.Call(ctx, %s, plugimpl.Void{})", methodName(m.Name))
			g.line("}")
		} else if shape.void {
			g.line("func (c *Client) %s(ctx context.Context, req %s) error {", shape.name, shape.request)
			g.line("\t_, err := c.raw.Call(ctx, %s, req)", methodName(m.Name))
			g.line("\treturn err")
			g.line("}")
		} else {
			g.line("func (c *Client) %s(ctx context.Context, req %s) (%s, error) {", shape.name, shape.request, shape.response)
			g.line("\treturn c.raw.Call(ctx, %s, req)", methodName(m.Name))
			g.line("}")
		}
		g.line("")
	}
}

func (g *generator) hasRawMethods() bool {
	return slices.ContainsFunc(g.schema.Methods, func(m plug.MethodInfo) bool {
		return isRaw(m.Response)
	})
}

func (g *generator) writeHTTPRoutes() {
	if !g.hasHTTP {
		return
	}

	g.line("// HTTPRoutes returns every HTTP binding declared by the schema.")
	g.line("func HTTPRoutes(server *plug.Server) []plughttp.Route {")
	g.line("\treturn []plughttp.Route{")
	for _, m := range g.methods {
		for _, b := range m.HTTP {
			g.line("\t\tplughttp.NewRoute(server, %s, plughttp.Binding{", methodName(m.Name))
			g.line("\t\t\tVerb: %s,", strconv.Quote(b.Verb))
			g.line("\t\t\tPath: %s,", strconv.Quote(b.Path))
			decoder := "nil"
			if len(m.Fields) > 0 {
				decoder = "decode" + names.GoMethod(m.Name) + "HTTP"
			}
			g.line("\t\t}, %s),", decoder)
		}
	}
	g.line("\t}")
	g.line("}")
	g.line("")
}

func codecName(name string) string { return "codec" + names.Go(name) }

func errorCodecName(name string) string { return "errors" + names.Go(name) }

func constructorIDName(name string) string { return "constructorID" + names.Go(name) }

func methodIDName(name string) string { return "methodID" + names.GoMethod(name) }

func methodName(name string) string { return "method" + names.GoMethod(name) }

func (g *generator) writeSchema() {
	s := g.schema
	g.line("// Schema describes the generated Plug service.")
	g.line("var Schema = plug.Schema{")
	g.line("\tPackage: %s,", strconv.Quote(s.Package))
	g.line("\tMajor: %d,", s.Major)
	g.line("\tFamily: plugimpl.FamilyFingerprint(%s, %d),", strconv.Quote(s.Package), s.Major)
	g.writeSchemaDoc("\t", s.Documentation)
	g.line("\tFingerprint: [32]byte{%s},", byteLiteral(s.Fingerprint[:]))
	g.line("\tSource: %s,", strconv.Quote(s.Source))
	g.line("\tPermissions: []plug.PermissionInfo{")
	for _, p := range s.Permissions {
		g.line("\t\t{")
		g.line("\t\t\tName: %s,", strconv.Quote(p.Name))
		g.writeSchemaDoc("\t\t\t", p.Documentation)
		g.line("\t\t},")
	}
	g.line("\t},")

	if len(s.Categories) > 0 {
		g.line("\tCategories: []plug.CategoryInfo{")
		for _, cat := range s.Categories {
			g.line("\t\t{")
			g.line("\t\t\tName: %s,", strconv.Quote(cat.Name))
			g.writeSchemaDoc("\t\t\t", cat.Documentation)
			if len(cat.Types) > 0 {
				g.line("\t\t\tTypes: []string{%s},", quotedStrings(cat.Types))
			}
			if len(cat.Methods) > 0 {
				g.line("\t\t\tMethods: []string{%s},", quotedStrings(cat.Methods))
			}
			g.line("\t\t},")
		}
		g.line("\t},")
	}

	g.line("\tTypes: []plug.TypeInfo{")
	for _, typ := range s.Types {
		g.line("\t\t{")
		g.line("\t\t\tName: %s,", strconv.Quote(typ.Name))
		g.writeSchemaDoc("\t\t\t", typ.Documentation)
		g.line("\t\t\tKind: %s,", typeKindLiteral(typ.Kind))
		if typ.Underlying != "" {
			g.line("\t\t\tUnderlying: %s,", strconv.Quote(typ.Underlying))
		}
		if typ.Error {
			g.line("\t\t\tError: true,")
		}
		if len(typ.Constructors) > 0 {
			g.line("\t\t\tConstructors: []plug.ConstructorInfo{")
			for _, c := range typ.Constructors {
				g.line("\t\t\t\t{")
				g.line("\t\t\t\t\tName: %s,", strconv.Quote(c.Name))
				g.writeSchemaDoc("\t\t\t\t\t", c.Documentation)
				g.line("\t\t\t\t\tID: 0x%08x,", c.ID)
				if c.HTTPStatus != 0 {
					g.line("\t\t\t\t\tHTTPStatus: %d,", c.HTTPStatus)
				}
				g.writeFieldInfo(c.Fields, "\t\t\t\t\t")
				g.line("\t\t\t\t},")
			}
			g.line("\t\t\t},")
		}
		g.line("\t\t},")
	}
	g.line("\t},")

	g.line("\tMethods: []plug.MethodInfo{")
	for _, m := range s.Methods {
		g.line("\t\t{")
		g.line("\t\t\tName: %s,", strconv.Quote(m.Name))
		g.writeSchemaDoc("\t\t\t", m.Documentation)
		g.line("\t\t\tID: 0x%08x,", m.ID)
		g.writeFieldInfo(m.Fields, "\t\t\t")
		g.line("\t\t\tResponse: %s,", typeExprLiteral(m.Response))
		if m.Error != "" {
			g.line("\t\t\tError: %s,", strconv.Quote(m.Error))
		}
		if m.Public {
			g.line("\t\t\tPublic: true,")
		}
		if m.Permission != "" {
			g.line("\t\t\tPermission: %s,", strconv.Quote(m.Permission))
		}
		if len(m.HTTP) > 0 {
			g.line("\t\t\tHTTP: []plug.HTTPBindingInfo{")
			for _, b := range m.HTTP {
				g.line("\t\t\t\t{")
				g.line("\t\t\t\t\tVerb: %s,", strconv.Quote(b.Verb))
				g.line("\t\t\t\t\tPath: %s,", strconv.Quote(b.Path))
				g.line("\t\t\t\t},")
			}
			g.line("\t\t\t},")
		}
		g.line("\t\t},")
	}
	g.line("\t},")
	g.line("}")
	g.line("")
}

func typeKindLiteral(kind plug.TypeKind) string {
	switch kind {
	case plug.TypeNewtype:
		return "plug.TypeNewtype"
	case plug.TypeRecord:
		return "plug.TypeRecord"
	case plug.TypeSum:
		return "plug.TypeSum"
	default:
		panic(fmt.Sprintf("unknown Plug type kind %d", kind))
	}
}

func (g *generator) writeFieldInfo(fields []plug.FieldInfo, indent string) {
	if len(fields) == 0 {
		return
	}

	g.line("%sFields: []plug.FieldInfo{", indent)
	for _, f := range fields {
		g.line("%s\t{", indent)
		g.line("%s\t\tName: %s,", indent, strconv.Quote(f.Name))
		g.writeSchemaDoc(indent+"\t\t", f.Documentation)
		g.line("%s\t\tType: %s,", indent, typeExprLiteral(f.Type))
		g.line("%s\t},", indent)
	}
	g.line("%s},", indent)
}

func (g *generator) writeSchemaDoc(indent, text string) {
	if text != "" {
		g.line("%sDocumentation: %s,", indent, strconv.Quote(text))
	}
}

func typeExprLiteral(expr plug.TypeExpr) string {
	var value string
	switch expr.Kind {
	case plug.TypeExprList:
		value = "plugimpl.ListType(" + typeExprLiteral(*expr.Element) + ")"
	case plug.TypeExprNamed:
		value = "plugimpl.NamedType(" + strconv.Quote(expr.Name) + ")"
	default:
		value = "plugimpl.PrimitiveType(" + strconv.Quote(expr.Name) + ")"
	}
	if expr.Optional {
		value = "plugimpl.OptionalType(" + value + ")"
	}
	return value
}

func quotedStrings(values []string) string {
	quoted := make([]string, len(values))
	for i, v := range values {
		quoted[i] = strconv.Quote(v)
	}
	return strings.Join(quoted, ", ")
}

func byteLiteral(value []byte) string {
	parts := make([]string, len(value))
	for i, b := range value {
		parts[i] = fmt.Sprintf("0x%02x", b)
	}
	return strings.Join(parts, ", ")
}

func (g *goGenerator) writeGoPackageDoc(title string) {
	g.doc("Package "+g.schema.Package, g.schema.Package, "contains generated "+title+".", g.schema.Documentation)
}
