// TypeScript returns deterministic TypeScript types and an HTTP client for s.
func TypeScript(s plug.Schema) ([]byte, error) {
	m := newModel(s)
	m.useHTTPMethods()
	g := tsGenerator{
		model:  m,
		indent: "  ",
		docs:   doc.NewParser(&s),
	}
	return g.generate(), nil
}

type tsGenerator struct {
	model
	emitter
}

func (g *tsGenerator) generate() []byte {
	g.line("// Code generated by plug; DO NOT EDIT.")
	g.line("")
	g.writePackageDoc()
	g.writeHTTPError()
	g.writeTypes()
	g.writeRequests()
	g.writeClient()
	return g.buf.Bytes()
}

func (g *tsGenerator) writePackageDoc() {
	doc := g.docs.Comment(g.schema.Documentation)
	if doc == "" {
		return
	}

	g.comments("", strings.Split(doc, "\n"))
	g.line("")
}

func (g *tsGenerator) writeTypes() {
	for _, nt := range g.newtypes {
		tsName := names.Go(nt.Name)
		g.doc(tsName, nt.Name, fmt.Sprintf("is the distinct Plug scalar %s.", nt.Name), nt.Documentation)
		g.line("export type %s = %s;", tsName, tsPrimitiveType(nt.Underlying))
		g.line("")
	}

	for _, name := range g.groupNames {
		ctors := g.types[name].Constructors
		if len(ctors) == 1 {
			var (
				c      = ctors[0]
				tsName = names.Go(name)
			)

			g.doc(tsName, c.Name, fmt.Sprintf("is the Plug record %s.", name), c.Documentation)
			if g.types[name].Error {
				g.writeErrorClass(tsName, c.Name, c.Fields, false)
			} else {
				g.writeInterface(tsName, c.Fields, "")
			}
			g.line("")
			continue
		}

		var (
			sumName = names.Go(name)
			sumDoc  = g.types[name].Documentation
		)

		var variantNames []string
		for _, c := range ctors {
			variant := names.Go(c.Name)
			variantNames = append(variantNames, variant)

			g.doc(variant, c.Name, fmt.Sprintf("is the %s variant of %s.", c.Name, name), c.Documentation)
			if g.types[name].Error {
				g.writeErrorClass(variant, c.Name, c.Fields, true)
			} else {
				discriminator := fmt.Sprintf("type: %s;", strconv.Quote(c.Name))
				g.writeInterface(variant, c.Fields, discriminator)
			}
			g.line("")
		}

		g.doc(sumName, name, fmt.Sprintf("is the sealed Plug sum %s.", name), sumDoc)
		declaration := fmt.Sprintf("export type %s = %s;", sumName, strings.Join(variantNames, " | "))
		if len(declaration) <= 80 {
			g.line("%s", declaration)
		} else {
			g.line("export type %s =", sumName)
			for i, variant := range variantNames {
				if i == len(variantNames)-1 {
					g.line("  | %s;", variant)
					continue
				}
				g.line("  | %s", variant)
			}
		}
		g.line("")
	}
}

func (g *tsGenerator) writeErrorClass(name, wireName string, fields []plug.FieldInfo, tagged bool) {
	if len(fields) == 0 {
		g.line("export class %s extends HTTPError {", name)
	} else {
		g.line("export class %s extends HTTPError<{", name)
		g.writeFields(fields)
		g.line("}> {")
	}
	if tagged {
		g.line("  readonly type: %s = %s;", strconv.Quote(wireName), strconv.Quote(wireName))
	}
	for _, f := range fields {
		if !g.errorField(f) {
			continue
		}
		var (
			propName  = f.Name
			fieldType = g.tsType(f.Type)
			modifier  = "readonly"
		)
		if f.Type.Optional {
			propName += "?"
		}
		if f.Name == "message" {
			modifier = "override readonly"
		}

		g.docIndented(names.Go(f.Name), f.Name, fmt.Sprintf("is the %s schema field.", f.Name), f.Documentation)
		g.line("  %s %s: %s;", modifier, propName, fieldType)
	}
	g.line("")

	g.line("  constructor(")
	g.line("    status: number,")
	g.line("    message: string,")
	g.line("    details?: Record<string, unknown>,")
	g.line("  ) {")
	if len(fields) == 0 {
		g.line("    super(status, %s, message, details);", strconv.Quote(wireName))
	} else {
		g.line("    super(status, %s, message, details as %s[\"details\"]);", strconv.Quote(wireName), name)
	}
	g.line("    this.name = %s;", strconv.Quote(name))
	for _, f := range fields {
		if !g.errorField(f) {
			continue
		}
		fieldType := g.tsType(f.Type)
		if f.Name == "message" {
			g.line("    this.message = (details?.message as %s) || message;", fieldType)
		} else {
			g.line("    this.%s = details?.%s as %s;", f.Name, f.Name, fieldType)
		}
	}
	g.line("  }")
	g.line("}")
}

// Error metadata stays on the class; conflicting schema fields stay in details.
func (g *tsGenerator) errorField(f plug.FieldInfo) bool {
	switch f.Name {
	case "message":
		base := f.Type.Name
		if typ, ok := g.types[base]; ok {
			base = typ.Underlying
		}
		return base == "string" && !f.Type.Optional
	case "name", "stack", "status", "code", "details", "cause", "constructor", "__proto__",
		"toString", "toLocaleString", "valueOf", "hasOwnProperty", "isPrototypeOf", "propertyIsEnumerable":
		return false
	default:
		return true
	}
}

func (g *tsGenerator) writeRequests() {
	for _, m := range g.methods {
		name := names.GoMethod(m.Name) + "Request"
		if len(m.Fields) == 0 {
			continue
		}

		g.line("// %s contains the request fields for %s.", name, m.Name)
		g.writeInterface(name, m.Fields, "")
		g.line("")
	}
}

func (g *tsGenerator) writeInterface(name string, fields []plug.FieldInfo, discriminator string) {
	g.line("export interface %s {", name)
	if discriminator != "" {
		g.line("  %s", discriminator)
	}
	g.writeFields(fields)
	g.line("}")
}

func (g *tsGenerator) writeFields(fields []plug.FieldInfo) {
	for _, f := range fields {
		propName := f.Name
		if f.Type.Optional {
			propName += "?"
		}

		g.docIndented(names.Go(f.Name), f.Name, fmt.Sprintf("is the %s schema field.", f.Name), f.Documentation)
		g.line("  %s: %s;", propName, g.tsType(f.Type))
	}
}

func (g *tsGenerator) writeHTTPError() {
	g.line("// HTTPError reports an unsuccessful HTTP response status.")
	g.line("export class HTTPError<D = unknown> extends Error {")
	g.line("  constructor(")
	g.line("    readonly status: number,")
	g.line("    readonly code: string,")
	g.line("    message: string,")
	g.line("    readonly details?: D,")
	g.line("  ) {")
	g.line("    super(")
	g.line("      code")
	g.line("        ? `http ${status} (${code}): ${message}`")
	g.line("        : `http ${status}: ${message}`,")
	g.line("    );")
	g.line("    this.name = \"HTTPError\";")
	g.line("  }")
	g.line("}")
	g.line("")
}

func (g *tsGenerator) writeClient() {
	g.line("// ClientOptions configures a Plug HTTP client.")
	g.line("export interface ClientOptions {")
	g.line("  // Custom fetch implementation. Defaults to global fetch.")
	g.line("  fetch?: typeof fetch;")
	g.line("  // Default headers sent with every request, or a function returning them.")
	g.line("  headers?: HeadersInit | (() => HeadersInit | Promise<HeadersInit>);")
	g.line("}")
	g.line("")

	g.line("// Client is the HTTP client for %s.", g.schema.Package)
	g.line("export class Client {")
	g.line("  constructor(")
	g.line("    private readonly baseURL: string,")
	g.line("    private readonly options: ClientOptions = {},")
	g.line("  ) {")
	g.line("    this.baseURL = baseURL.replace(/\\/+$/, \"\");")
	g.line("  }")
	g.line("")
	g.line("  private async request<T = void>(")
	g.line("    method: string,")
	g.line("    path: string,")
	g.line("    opts?: { query?: object; body?: unknown },")
	g.line("  ): Promise<T> {")
	g.line("    let url = `${this.baseURL}${path}`;")
	g.line("    if (opts?.query) {")
	g.line("      const params = new URLSearchParams();")
	g.line("      for (const [key, value] of Object.entries(opts.query)) {")
	g.line("        if (value == null) continue;")
	g.line("        if (Array.isArray(value)) {")
	g.line("          for (const item of value) {")
	g.line("            if (item != null) params.append(key, String(item));")
	g.line("          }")
	g.line("        } else {")
	g.line("          params.set(key, String(value));")
	g.line("        }")
	g.line("      }")
	g.line("      const qs = params.toString();")
	g.line("      if (qs) url += `?${qs}`;")
	g.line("    }")
	g.line("    const headers = new Headers(")
	g.line("      typeof this.options.headers === \"function\"")
	g.line("        ? await this.options.headers()")
	g.line("        : this.options.headers,")
	g.line("    );")
	g.line("    let bodyText: string | undefined;")
	g.line("    if (opts?.body !== undefined) {")
	g.line("      headers.set(\"Content-Type\", \"application/json\");")
	g.line("      bodyText = JSON.stringify(opts.body);")
	g.line("    }")
	g.line("    const fetchFn = this.options.fetch ?? fetch;")
	g.line("    const res = await fetchFn(url, {")
	g.line("      method,")
	g.line("      headers,")
	g.line("      body: bodyText,")
	g.line("    });")

	errorConstructors := g.errorConstructors

	g.line("    if (!res.ok) {")
	g.line("      const err = await res.json().catch(() => ({}));")
	g.line("      const code = typeof err?.code === \"string\" ? err.code : \"\";")
	g.line("      const message = typeof err?.message === \"string\"")
	g.line("        ? err.message")
	g.line("        : (res.statusText || String(res.status));")
	if len(errorConstructors) > 0 {
		g.line("      switch (code) {")
		for _, c := range errorConstructors {
			name := names.Go(c.Name)
			if len(g.types[c.result].Constructors) == 1 {
				name = names.Go(c.result)
			}
			g.line("        case %s:", strconv.Quote(c.Name))
			g.line("          throw new %s(res.status, message, err?.details);", name)
		}
		g.line("        default:")
		g.line("          throw new HTTPError(res.status, code, message, err?.details);")
		g.line("      }")
	} else {
		g.line("      throw new HTTPError(res.status, code, message, err?.details);")
	}
	g.line("    }")
	g.line("    if (res.status === 204 || res.headers.get(\"content-length\") === \"0\") {")
	g.line("      return undefined as T;")
	g.line("    }")
	g.line("    return (await res.json()) as T;")
	g.line("  }")

	for _, http := range g.httpMethods {
		g.line("")
		g.writeClientMethod(http)
	}
	g.line("}")
}

func (g *tsGenerator) writeClientMethod(http httpMethod) {
	var (
		m           = http.method
		binding     = http.binding
		methodName  = names.TypeScriptMethod(m.Name)
		reqTypeName = names.GoMethod(m.Name) + "Request"
		hasReq      = len(m.Fields) > 0
		isVoid      = m.Response.Name == "void" && m.Response.Element == nil && !m.Response.Optional
		resType     = "void"
	)
	if !isVoid {
		resType = g.tsType(m.Response)
		if m.Response.Optional {
			resType += " | null"
		}
	}

	var (
		pathParams  = make([]string, 0, len(http.pathFields))
		queryFields = http.queryFields
		bodyFields  = http.bodyFields
	)
	for _, f := range http.pathFields {
		pathParams = append(pathParams, f.Name)
	}

	g.docIndented(methodName, m.Name, fmt.Sprintf("invokes %s via HTTP %s %s.", m.Name, binding.Verb, binding.Path), m.Documentation)

	allOptional := true
	for _, f := range m.Fields {
		if !f.Type.Optional {
			allOptional = false
			break
		}
	}

	if hasReq {
		if allOptional {
			g.line("  async %s(req: %s = {}): Promise<%s> {", methodName, reqTypeName, resType)
		} else {
			g.line("  async %s(req: %s): Promise<%s> {", methodName, reqTypeName, resType)
		}
	} else {
		g.line("  async %s(): Promise<%s> {", methodName, resType)
	}

	var (
		hasDestructured bool
		optParts        []string
	)

	if len(queryFields) > 0 {
		if len(pathParams) > 0 {
			g.line("    const { %s, ...query } = req;", strings.Join(pathParams, ", "))
			hasDestructured = true
			optParts = append(optParts, "query")
		} else {
			optParts = append(optParts, "query: req")
		}
	} else if len(bodyFields) > 0 {
		if len(pathParams) > 0 {
			g.line("    const { %s, ...body } = req;", strings.Join(pathParams, ", "))
			hasDestructured = true
			optParts = append(optParts, "body")
		} else {
			optParts = append(optParts, "body: req")
		}
	}

	pathExpr := ""
	if len(pathParams) > 0 {
		pathTemplate := escapeTemplate(binding.Path)
		for _, param := range pathParams {
			varRef := "req." + param
			if hasDestructured {
				varRef = param
			}
			placeholder := "{" + param + "}"
			if strings.Contains(binding.Path, "{"+param+"...}") {
				placeholder = "{" + param + "...}"
				pathTemplate = strings.ReplaceAll(pathTemplate, placeholder, fmt.Sprintf("${String(%s ?? \"\").split(\"/\").map(encodeURIComponent).join(\"/\")}", varRef))
			} else {
				pathTemplate = strings.ReplaceAll(pathTemplate, placeholder, fmt.Sprintf("${encodeURIComponent(String(%s))}", varRef))
			}
		}
		pathExpr = "`" + pathTemplate + "`"
	} else {
		pathExpr = strconv.Quote(binding.Path)
	}

	callArgs := []string{strconv.Quote(binding.Verb), pathExpr}
	if len(optParts) > 0 {
		callArgs = append(callArgs, "{ "+strings.Join(optParts, ", ")+" }")
	}

	requestCall := "this.request"
	if !isVoid {
		requestCall += "<" + resType + ">"
	}
	call := fmt.Sprintf("return await %s(%s);", requestCall, strings.Join(callArgs, ", "))
	if len(call)+4 <= 80 {
		g.line("    %s", call)
	} else {
		g.line("    return await %s(", requestCall)
		for _, arg := range callArgs {
			g.line("      %s,", arg)
		}
		g.line("    );")
	}
	g.line("  }")
}

func (g *tsGenerator) tsType(ref plug.TypeExpr) string {
	var result string
	if ref.Element != nil {
		result = g.tsType(*ref.Element) + "[]"
	} else if ref.Kind == plug.TypeExprPrimitive {
		result = tsPrimitiveType(ref.Name)
	} else {
		result = names.Go(ref.Name)
	}
	return result
}

func tsPrimitiveType(name string) string {
	switch name {
	case "bool":
		return "boolean"
	case "bytes", "string":
		return "string"
	case "f64", "i32", "i64", "u32", "u64":
		return "number"
	case "void":
		return "void"
	default:
		return "unknown"
	}
}

// escapeTemplate quotes literal text before inserting path parameter expressions.
func escapeTemplate(s string) string {
	return strings.NewReplacer(
		"\\", "\\\\", "`", "\\`", "$", "\\$",
		"\r", "\\r", "\n", "\\n", "\u2028", "\\u2028", "\u2029", "\\u2029",
	).Replace(s)
}
