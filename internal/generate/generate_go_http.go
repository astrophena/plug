// GoHTTPClient returns deterministic Go HTTP client bindings using only the
// standard library.
func GoHTTPClient(s plug.Schema) ([]byte, error) {
	m := newModel(s)
	m.useHTTPMethods()
	g := goHTTPGenerator{
		goGenerator: newGoGenerator(m, false),
	}

	return formatGo(g.generate(), "Go HTTP client")
}

type goHTTPGenerator struct {
	goGenerator
}

func (g *goHTTPGenerator) generate() []byte {
	g.line("// Code generated by plug; DO NOT EDIT.")
	g.line("")
	g.writeGoPackageDoc("Plug HTTP client bindings")
	g.line("package %s", g.schema.Package)
	g.line("")
	g.writeImports()
	g.writeTypes()
	g.writeRequests()
	g.writeJSON()
	if g.hasOptional() {
		g.writeOption()
	}
	g.writeHTTPError()
	g.writeClient()
	return g.buf.Bytes()
}

func (g *goHTTPGenerator) writeImports() {
	g.line("import (")
	g.line("\t\"bytes\"")
	g.line("\t\"context\"")
	g.line("\t\"encoding/json/jsontext\"")
	g.line("\t\"encoding/json/v2\"")
	g.line("\t\"fmt\"")
	g.line("\t\"io\"")
	g.line("\t\"net/http\"")
	g.line("\t\"strings\"")
	for _, path := range g.urlImports() {
		g.line("\t%q", path)
	}
	g.line(")")
	g.line("")
}

func (g *goHTTPGenerator) writeOption() {
	g.line("// Option holds a value that may be absent. Its zero value is None.")
	g.line("type Option[T any] struct {")
	g.line("\tvalue T")
	g.line("\tset   bool")
	g.line("}")
	g.line("")

	g.line("// Some returns an Option containing value.")
	g.line("func Some[T any](v T) Option[T] {")
	g.line("\treturn Option[T]{value: v, set: true}")
	g.line("}")
	g.line("")

	g.line("// Value returns the contained value and whether it is present.")
	g.line("func (o Option[T]) Value() (T, bool) { return o.value, o.set }")
	g.line("")

	g.line("// IsZero reports whether the option is absent for encoders that honor Go's zero-value convention.")
	g.line("func (o Option[T]) IsZero() bool { return !o.set }")
	g.line("")

	g.line("// MarshalJSON encodes None as null and Some as its contained value.")
	g.line("func (o Option[T]) MarshalJSON() ([]byte, error) {")
	g.line("\tif !o.set {")
	g.line("\t\treturn []byte(\"null\"), nil")
	g.line("\t}")
	g.line("\treturn json.Marshal(o.value)")
	g.line("}")
	g.line("")

	g.line("// UnmarshalJSON decodes null as None and any other value as Some.")
	g.line("func (o *Option[T]) UnmarshalJSON(data []byte) error {")
	g.line("\tif bytes.Equal(bytes.TrimSpace(data), []byte(\"null\")) {")
	g.line("\t\t*o = Option[T]{}")
	g.line("\t\treturn nil")
	g.line("\t}")
	g.line("\tvar v T")
	g.line("\tif err := json.Unmarshal(data, &v); err != nil {")
	g.line("\t\treturn err")
	g.line("\t}")
	g.line("\t*o = Some(v)")
	g.line("\treturn nil")
	g.line("}")
	g.line("")
}

func (g *goHTTPGenerator) writeHTTPError() {
	g.line("// HTTPError reports an unsuccessful HTTP response status.")
	g.line("type HTTPError struct {")
	g.line("\tStatusCode int")
	g.line("\tCode       string")
	g.line("\tMessage    string")
	g.line("\tBody       []byte")
	g.line("}")
	g.line("")

	g.line("func (e *HTTPError) Error() string {")
	g.line("\tif e.Code != \"\" {")
	g.line("\t\treturn fmt.Sprintf(\"http %%d (%%s): %%s\", e.StatusCode, e.Code, e.Message)")
	g.line("\t}")
	g.line("\treturn fmt.Sprintf(\"http %%d: %%s\", e.StatusCode, e.Message)")
	g.line("}")
	g.line("")
}

func (g *goHTTPGenerator) writeClient() {
	g.line("// Client is the HTTP client for %s.", g.schema.Package)
	g.line("type Client struct {")
	g.line("\tbaseURL    string")
	g.line("\thttpClient *http.Client")
	g.line("\theaders    http.Header")
	g.line("}")
	g.line("")

	g.line("// ClientOption configures a Client.")
	g.line("type ClientOption func(*Client)")
	g.line("")

	g.line("// WithHTTPClient sets the underlying HTTP client.")
	g.line("func WithHTTPClient(client *http.Client) ClientOption {")
	g.line("\treturn func(c *Client) {")
	g.line("\t\tif client != nil {")
	g.line("\t\t\tc.httpClient = client")
	g.line("\t\t}")
	g.line("\t}")
	g.line("}")
	g.line("")

	g.line("// WithHeader adds a default header to all requests.")
	g.line("func WithHeader(key, value string) ClientOption {")
	g.line("\treturn func(c *Client) {")
	g.line("\t\tif c.headers == nil {")
	g.line("\t\t\tc.headers = make(http.Header)")
	g.line("\t\t}")
	g.line("\t\tc.headers.Add(key, value)")
	g.line("\t}")
	g.line("}")
	g.line("")

	g.line("// NewClient returns a new Client for baseURL.")
	g.line("func NewClient(baseURL string, opts ...ClientOption) *Client {")
	g.line("\tc := &Client{")
	g.line("\t\tbaseURL:    strings.TrimRight(baseURL, \"/\"),")
	g.line("\t\thttpClient: http.DefaultClient,")
	g.line("\t\theaders:    make(http.Header),")
	g.line("\t}")
	g.line("\tfor _, opt := range opts {")
	g.line("\t\topt(c)")
	g.line("\t}")
	g.line("\treturn c")
	g.line("}")
	g.line("")

	g.writeClientDo()
	g.writeClientDecodeError()

	for _, http := range g.httpMethods {
		g.writeClientMethod(http)
	}
}

func (g *goHTTPGenerator) writeClientDo() {
	g.line("func (c *Client) do(ctx context.Context, method, path string, body, target any) error {")
	g.line("\tvar bodyReader io.Reader")
	g.line("\tif body != nil {")
	g.line("\t\tbodyBytes, err := json.Marshal(body)")
	g.line("\t\tif err != nil {")
	g.line("\t\t\treturn fmt.Errorf(\"marshal request: %%w\", err)")
	g.line("\t\t}")
	g.line("\t\tbodyReader = bytes.NewReader(bodyBytes)")
	g.line("\t}")

	g.line("\treq, err := http.NewRequestWithContext(ctx, method, c.baseURL+path, bodyReader)")
	g.line("\tif err != nil {")
	g.line("\t\treturn fmt.Errorf(\"create request: %%w\", err)")
	g.line("\t}")
	g.line("\tif c.headers != nil {")
	g.line("\t\treq.Header = c.headers.Clone()")
	g.line("\t}")
	g.line("\tif body != nil && req.Header.Get(\"Content-Type\") == \"\" {")
	g.line("\t\treq.Header.Set(\"Content-Type\", \"application/json\")")
	g.line("\t}")

	g.line("\tresp, err := c.httpClient.Do(req)")
	g.line("\tif err != nil {")
	g.line("\t\treturn fmt.Errorf(\"send request: %%w\", err)")
	g.line("\t}")
	g.line("\tdefer resp.Body.Close()")
	g.line("")

	g.line("\tif resp.StatusCode < 200 || resp.StatusCode >= 300 {")
	g.line("\t\trespBody, readErr := io.ReadAll(resp.Body)")
	g.line("\t\tif readErr != nil {")
	g.line("\t\t\treturn fmt.Errorf(\"read error response: %%w\", readErr)")
	g.line("\t\t}")
	g.line("\t\tvar envelope struct {")
	g.line("\t\t\tCode    string          `json:\"code\"`")
	g.line("\t\t\tMessage string          `json:\"message\"`")
	g.line("\t\t\tDetails jsontext.Value `json:\"details\"`")
	g.line("\t\t}")
	g.line("\t\tjson.Unmarshal(respBody, &envelope)")
	g.line("\t\tif appErr := c.decodeError(envelope.Code, envelope.Details); appErr != nil {")
	g.line("\t\t\treturn appErr")
	g.line("\t\t}")
	g.line("\t\tmsg := envelope.Message")
	g.line("\t\tif msg == \"\" {")
	g.line("\t\t\tmsg = http.StatusText(resp.StatusCode)")
	g.line("\t\t}")
	g.line("\t\treturn &HTTPError{")
	g.line("\t\t\tStatusCode: resp.StatusCode,")
	g.line("\t\t\tCode:       envelope.Code,")
	g.line("\t\t\tMessage:    msg,")
	g.line("\t\t\tBody:       respBody,")
	g.line("\t\t}")
	g.line("\t}")

	g.line("\tif target == nil {")
	g.line("\t\tio.Copy(io.Discard, resp.Body)")
	g.line("\t\treturn nil")
	g.line("\t}")
	g.line("\tif err := json.UnmarshalRead(resp.Body, target); err != nil {")
	g.line("\t\treturn fmt.Errorf(\"decode response: %%w\", err)")
	g.line("\t}")
	g.line("\treturn nil")
	g.line("}")
	g.line("")
}

func (g *goHTTPGenerator) writeClientDecodeError() {
	errorConstructors := g.errorConstructors

	if len(errorConstructors) == 0 {
		g.line("func (*Client) decodeError(string, jsontext.Value) error {")
		g.line("\treturn nil")
		g.line("}")
		g.line("")
		return
	}

	g.line("func (*Client) decodeError(code string, details jsontext.Value) error {")
	g.line("\tswitch code {")
	for _, c := range errorConstructors {
		typeName := names.Go(c.Name)
		if len(g.types[c.result].Constructors) == 1 {
			typeName = names.Go(c.result)
		}
		g.line("\tcase %s:", strconv.Quote(c.Name))
		g.line("\t\tvar appErr %s", typeName)
		g.line("\t\tif len(details) > 0 && string(details) != \"null\" {")
		g.line("\t\t\tjson.Unmarshal(details, &appErr)")
		g.line("\t\t}")
		g.line("\t\treturn &appErr")
	}
	g.line("\tdefault:")
	g.line("\t\treturn nil")
	g.line("\t}")
	g.line("}")
	g.line("")
}

func (g *goHTTPGenerator) writeClientMethod(http httpMethod) {
	var (
		m           = http.method
		binding     = http.binding
		shape       = g.methodShape(m)
		queryFields = http.queryFields
		hasReqBody  = len(http.bodyFields) > 0
	)

	g.doc(shape.name, m.Name, fmt.Sprintf("invokes %s via HTTP %s %s.", m.Name, binding.Verb, binding.Path), m.Documentation)
	switch {
	case shape.noRequest && shape.void:
		g.line("func (c *Client) %s(ctx context.Context) error {", shape.name)
	case shape.noRequest:
		g.line("func (c *Client) %s(ctx context.Context) (%s, error) {", shape.name, shape.response)
	case shape.void:
		g.line("func (c *Client) %s(ctx context.Context, req %s) error {", shape.name, shape.request)
	default:
		g.line("func (c *Client) %s(ctx context.Context, req %s) (%s, error) {", shape.name, shape.request, shape.response)
	}

	bodyArg := "nil"
	if hasReqBody {
		bodyArg = "req"
	}

	hasURLParams := len(http.pathFields) > 0 || len(queryFields) > 0
	pathArg := strconv.Quote(binding.Path)
	if hasURLParams {
		pathArg = "path"
		g.line("\tpath := %s", strconv.Quote(binding.Path))
		for _, field := range http.pathFields {
			value := "req." + names.Go(field.Name)
			ref := field.Type
			if ref.Optional {
				g.line("\t%s, _ := %s.Value()", field.Name+"Value", value)
				value = field.Name + "Value"
				ref.Optional = false
			}
			formatExpr := g.scalarFormatExpr(value, ref)
			placeholder := "{" + field.Name + "}"
			if strings.Contains(binding.Path, "{"+field.Name+"...}") {
				placeholder = "{" + field.Name + "...}"
				g.line("\t%sSegments := strings.Split(%s, \"/\")", field.Name, formatExpr)
				g.line("\tfor i := range %sSegments {", field.Name)
				g.line("\t\t%sSegments[i] = url.PathEscape(%sSegments[i])", field.Name, field.Name)
				g.line("\t}")
				g.line("\tpath = strings.ReplaceAll(path, %s, strings.Join(%sSegments, \"/\"))", strconv.Quote(placeholder), field.Name)
			} else {
				g.line("\tpath = strings.ReplaceAll(path, %s, url.PathEscape(%s))", strconv.Quote(placeholder), formatExpr)
			}
		}
		if len(queryFields) > 0 {
			g.line("\tquery := make(url.Values)")
			for _, f := range queryFields {
				var (
					fieldName = names.Go(f.Name)
					paramKey  = strconv.Quote(f.Name)
				)
				if f.Type.Optional {
					elemType := f.Type
					elemType.Optional = false
					g.line("\tif v, ok := req.%s.Value(); ok {", fieldName)
					g.writeQueryField("\t\t", paramKey, "v", elemType)
					g.line("\t}")
				} else {
					g.writeQueryField("\t", paramKey, "req."+fieldName, f.Type)
				}
			}
			g.line("\tif q := query.Encode(); q != \"\" {")
			g.line("\t\tpath += \"?\" + q")
			g.line("\t}")
		}
	}

	verbArg := strconv.Quote(binding.Verb)
	if shape.void {
		g.line("\treturn c.do(ctx, %s, %s, %s, nil)", verbArg, pathArg, bodyArg)
		g.line("}")
		g.line("")
		return
	}

	g.line("\tvar (")
	g.line("\t\tzero %s", shape.response)
	g.line("\t\tresult %s", shape.response)
	g.line("\t)")
	if g.typeContainsSum(m.Response) {
		g.line("\tvar data jsontext.Value")
		g.line("\tif err := c.do(ctx, %s, %s, %s, &data); err != nil {", verbArg, pathArg, bodyArg)
		g.line("\t\treturn zero, err")
		g.line("\t}")
		g.line("\tdata = bytes.TrimSpace(data)")
		var counter int
		g.writeJSONDecode(m.Response, "result", "data", "\t", "response", "zero, ", &counter)
	} else {
		g.line("\tif err := c.do(ctx, %s, %s, %s, &result); err != nil {", verbArg, pathArg, bodyArg)
		g.line("\t\treturn zero, err")
		g.line("\t}")
	}
	g.line("\treturn result, nil")
	g.line("}")
	g.line("")
}

func (g *goHTTPGenerator) writeQueryField(indent, key, value string, ref plug.TypeExpr) {
	if ref.Element != nil {
		g.line("%sfor _, item := range %s {", indent, value)
		g.line("%s\tquery.Add(%s, %s)", indent, key, g.scalarFormatExpr("item", *ref.Element))
		g.line("%s}", indent)
		return
	}
	g.line("%squery.Set(%s, %s)", indent, key, g.scalarFormatExpr(value, ref))
}

func (g *goHTTPGenerator) scalarFormatExpr(expr string, ref plug.TypeExpr) string {
	base := g.underlyingPrimitive(ref.Name)
	switch base {
	case "string":
		return "string(" + expr + ")"
	case "bool":
		return "strconv.FormatBool(bool(" + expr + "))"
	case "i32", "i64":
		return "strconv.FormatInt(int64(" + expr + "), 10)"
	case "u32", "u64":
		return "strconv.FormatUint(uint64(" + expr + "), 10)"
	case "f64":
		return "strconv.FormatFloat(float64(" + expr + "), 'g', -1, 64)"
	case "bytes":
		return "base64.StdEncoding.EncodeToString(" + expr + ")"
	default:
		return "fmt.Sprint(" + expr + ")"
	}
}

func (g *goHTTPGenerator) underlyingPrimitive(typeName string) string {
	if typ := g.types[typeName]; typ.Kind == plug.TypeNewtype {
		return typ.Underlying
	}
	return typeName
}

func (g *goHTTPGenerator) hasOptional() bool {
	for _, c := range g.constructors {
		for _, f := range c.Fields {
			if f.Type.Optional {
				return true
			}
		}
	}
	for _, m := range g.methods {
		for _, f := range m.Fields {
			if f.Type.Optional {
				return true
			}
		}
		if m.Response.Optional {
			return true
		}
	}
	return false
}

func (g *goHTTPGenerator) urlImports() []string {
	var useURL, useBase64, useStrconv bool
	for _, m := range g.httpMethods {
		for _, fields := range [][]plug.FieldInfo{m.pathFields, m.queryFields} {
			useURL = useURL || len(fields) > 0
			for _, field := range fields {
				ref := field.Type
				if ref.Element != nil {
					ref = *ref.Element
				}
				switch g.underlyingPrimitive(ref.Name) {
				case "bytes":
					useBase64 = true
				case "bool", "i32", "i64", "u32", "u64", "f64":
					useStrconv = true
				}
			}
		}
	}

	var imports []string
	if useURL {
		imports = append(imports, "net/url")
	}
	if useBase64 {
		imports = append(imports, "encoding/base64")
	}
	if useStrconv {
		imports = append(imports, "strconv")
	}
	return imports
}
